/// Line and column of the reader's **syntax** errors against Java.
///
/// Java reports the position via Jackson (`JsonProcessingException.getLocation()`), and that
/// is **not the place of the error**, but the end of the last event Jackson received from SnakeYAML
/// (`YAMLParser.currentLocation()` = `_lastEvent.getEndMark()` + 1). Hence
/// `a: [1, 2` reports 1:9 (after `2`), `a: !! 1` 1:2 (after the key `a`) and `%YAML 1.2 junk`
/// 1:1. See `JavaYamlErrorLocator`.
///
/// The table is **measured on Java** (probe `ProbeErr`, `YamlObjectMapper.create()
/// .readTree(InputStream)`, a maintainer-only probe): all inputs on which
/// our reader reports `.syntax` and Java an error, from the existing reader tests, from a separate
/// table, from the `throw` places in `YamlParser` not yet tested and their variants
/// with multi-character graphemes before the error (`e` + U+0301, emoji, flag, emoji
/// with a skin tone) — the column is counted in **code points**.
@Suite struct YamlSyntaxErrorPositionTests {

    @Test func measuredJavaPositions() {
        var mismatches: [String] = []
        for (text, line, column) in Self.measured {
            do {
                _ = try YamlParser.parse(text)
                mismatches.append("\(text.debugDescription): passes, Java \(line):\(column)")
            } catch let error as YamlError {
                if error.kind != .syntax || error.line != line || error.column != column {
                    mismatches.append("\(text.debugDescription): \(error.kind) \(error.line):\(error.column), Java \(line):\(column)")
                }
            } catch {
                mismatches.append("\(text.debugDescription): \(error)")
            }
        }
        #expect(mismatches.isEmpty, "\(mismatches.count) of \(Self.measured.count):\n\(mismatches.prefix(40).joined(separator: "\n"))")
    }

    /// The same input through `parseDocument` (the decoder path) reports the same position.
    @Test func parseDocumentReportsSamePosition() {
        var mismatches: [String] = []
        for (text, line, column) in Self.measured {
            do {
                _ = try YamlParser.parseDocument(text)
                mismatches.append("\(text.debugDescription): passes")
            } catch let error as YamlError {
                if error.line != line || error.column != column {
                    mismatches.append("\(text.debugDescription): \(error.line):\(error.column), Java \(line):\(column)")
                }
            } catch {
                mismatches.append("\(text.debugDescription): \(error)")
            }
        }
        #expect(mismatches.isEmpty, "\(mismatches.count) of \(Self.measured.count):\n\(mismatches.prefix(40).joined(separator: "\n"))")
    }

    /// A table of cases, listed separately so it is visible what was fixed.
    @Test func briefCases() {
        let cases: [(String, Int, Int)] = [
            ("a: [", 1, 5),
            ("id: abc\nbands: [", 2, 9),
            ("a: [1, 2\n", 1, 9),
            ("id: t\n? [a]\n: 1\n", 2, 4),
            ("id:\tt", 1, 3),
        ]
        for (text, line, column) in cases {
            #expect(throws: YamlError(kind: .syntax, message: message(of: text), line: line, column: column)) {
                _ = try YamlParser.parse(text)
            }
        }
    }

    private func message(of text: String) -> String {
        do { _ = try YamlParser.parse(text) } catch let error as YamlError { return error.message } catch {}
        return ""
    }

    /// Errors that Jackson throws only on number conversion: the end of the scalar, not the start
    /// (previously a recorded divergence "error column at `!!float`").
    @Test func numberDecodeFailuresPointPastTheScalar() {
        let cases: [(String, Int, Int)] = [
            ("s: .inf\n", 1, 8),
            ("a: !!float abc\n", 1, 15),
            ("a: !!float .inf\n", 1, 16),
            ("d: 1:30.5\n", 1, 10),
            ("a: [.inf]\n", 1, 9),
            ("zzz: .inf\ns: a\n", 1, 10),
        ]
        for (text, line, column) in cases {
            do {
                _ = try YamlParser.parse(text)
                Issue.record("\(text.debugDescription): passes")
            } catch let error as YamlError {
                #expect(error.kind == .syntax)
                #expect(error.line == line && error.column == column,
                        "\(text.debugDescription): \(error.line):\(error.column)")
            } catch {
                Issue.record("\(error)")
            }
        }
    }

    /// An error that Java does not have (we reject more than it does) keeps the position of our reader
    /// in code points — walking like Java finds nothing there.
    @Test func divergentRejectionKeepsOwnPosition() {
        // `&x: 1` is read by Java as an empty key (a recorded divergence "anchor
        // glued to the next character"); we report 1:3.
        #expect(throws: YamlError(kind: .syntax, message: message(of: "&x: 1\n"), line: 1, column: 3)) {
            _ = try YamlParser.parse("&x: 1\n")
        }
        guard case .success = JavaYamlErrorLocator.locate("&x: 1\n") else {
            Issue.record("Java „&x: 1“ reads without an error")
            return
        }
        // The own position is in code points too: `a: &x"q"` is read by Java (the value
        // disappears), we report an anchor glued to a quote — after an `é` of two points
        // and after a flag one column further than after `a`.
        for (text, column) in [("a: &x\"q\"\n", 6), ("e\u{301}: &x\"q\"\n", 7),
                               ("\u{1F1E8}\u{1F1FF}: &x\"q\"\n", 7)] {
            #expect(throws: YamlError(kind: .syntax, message: message(of: text), line: 1, column: column)) {
                _ = try YamlParser.parse(text)
            }
        }
    }

